package control

import (
	"fmt"
	"net/url"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

func GenerateConfig(st State) ([]byte, error) {
	if err := validateSettings(st.Settings); err != nil {
		return nil, err
	}
	settings := st.Settings
	controller, _ := url.Parse(settings.ControllerURL)
	listeners := []map[string]any{}
	proxies := []map[string]any{}
	used := map[int]bool{}
	for _, n := range st.Nodes {
		if !n.Enabled || !n.Available {
			continue
		}
		if n.Port < 1024 || n.Port > 65535 || used[n.Port] {
			return nil, fmt.Errorf("发现无效或重复的入口端口")
		}
		used[n.Port] = true
		if fmt.Sprint(n.Port) == controller.Port() {
			return nil, fmt.Errorf("节点入口端口与控制器冲突")
		}
		p := map[string]any{}
		for k, v := range n.Config {
			p[k] = v
		}
		p["name"] = configName(n)
		proxies = append(proxies, p)
		listeners = append(listeners, map[string]any{"name": fmt.Sprintf("in-%d", n.Port), "type": "mixed", "listen": settings.ListenHost, "port": n.Port, "udp": settings.UDP, "proxy": configName(n), "users": []map[string]string{{"username": settings.Username, "password": settings.Password}}})
	}
	config := map[string]any{
		"mode": "rule", "log-level": "info", "ipv6": false, "allow-lan": true,
		"external-controller": controller.Host, "secret": settings.ControllerSecret,
		"listeners": listeners, "proxies": proxies, "rules": []string{"MATCH,REJECT"},
		"profile": map[string]bool{"store-selected": false},
	}
	data, err := yaml.Marshal(config)
	if err != nil {
		return nil, fmt.Errorf("节点包含不支持的配置字段")
	}
	return append([]byte("# Generated by PortPilot. Contains credentials; keep private.\n"), data...), nil
}

func ExportLinks(st State, protocol string, ids map[string]bool) (string, error) {
	if protocol != "http" && protocol != "socks5h" {
		return "", fmt.Errorf("协议仅支持 http 或 socks5h")
	}
	nodes := append([]Node(nil), st.Nodes...)
	sort.Slice(nodes, func(i, j int) bool { return nodes[i].Port < nodes[j].Port })
	links := []string{}
	for _, n := range nodes {
		if n.Enabled && n.Available && (len(ids) == 0 || ids[n.ID]) {
			links = append(links, proxyURL(st.Settings, n, protocol))
		}
	}
	return strings.Join(links, "\n"), nil
}
